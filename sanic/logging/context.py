"""Request-scoped audit correlation context.

The value stored here is deliberately independent from any client supplied
request identifier. It is created once when a request object is built and is
never overwritten by request headers, query arguments, bodies, or logging
``extra`` mappings.
"""

from __future__ import annotations

import re

from contextlib import contextmanager
from contextvars import ContextVar, Token
from dataclasses import dataclass
from secrets import token_hex


UNSAFE_LOG_CHARACTERS = re.compile(r"[\x00-\x1f\x7f\ud800-\udfff]")
DEFAULT_EXTERNAL_ID_MAX_LENGTH = 64


def normalize_external_id(
    value: str | None, max_length: int = DEFAULT_EXTERNAL_ID_MAX_LENGTH
) -> str | None:
    """Return a bounded, log-safe external request identifier.

    The value is treated as untrusted input: control characters (including
    lone surrogates that can break log encoders) are removed to prevent log
    forging and the result is truncated to ``max_length``. An empty value is
    reported as ``None`` so that "not supplied" stays distinguishable from an
    explicitly empty header.
    """

    if value is None:
        return None

    value = UNSAFE_LOG_CHARACTERS.sub("", str(value)).strip()
    if not value:
        return None

    try:
        max_length = int(max_length)
    except (TypeError, ValueError):
        max_length = DEFAULT_EXTERNAL_ID_MAX_LENGTH

    if max_length <= 0:
        return None
    return value[:max_length]


@dataclass(frozen=True)
class RequestAuditContext:
    """Immutable audit fields that belong to exactly one request."""

    internal_id: str
    external_id: str | None = None


_current: ContextVar[RequestAuditContext | None] = ContextVar(
    "sanic.request_audit", default=None
)


def generate_internal_id() -> str:
    """Generate an opaque internal correlation key.

    This intentionally does not use ``uuid.uuid4`` because the public
    ``Request.generate_id`` hook is user supplied and may be monkeypatched or
    customized. The audit key must be generated by Sanic itself.
    """

    return token_hex(16)


def bind_request_audit(
    internal_id: str, external_id: str | None = None
) -> Token:
    """Attach audit fields to the current context and return a reset token."""

    return _current.set(
        RequestAuditContext(
            internal_id=internal_id,
            external_id=external_id,
        )
    )


def reset_request_audit(token: Token) -> None:
    """Restore the previous audit context."""

    _current.reset(token)


def current_request_audit() -> RequestAuditContext | None:
    """Return the audit context for the active request, if any."""

    return _current.get()


@contextmanager
def audit_scope(internal_id: str | None, external_id: str | None = None):
    """Temporarily bind audit fields for protocol level log events.

    Connection level events (for example a disconnect after the request
    finished) happen outside of the request ContextVar lifetime. This helper
    lets those events still report the key that belonged to their request
    without leaving it bound afterwards.
    """

    if not internal_id:
        yield
        return
    token = bind_request_audit(internal_id, external_id)
    try:
        yield
    finally:
        reset_request_audit(token)
